#!/usr/bin/env python3
"""Writes THIRD_PARTY_NOTICES.md: what YT Grabber bundles or downloads, with each licence and version.

    python tools/gen_notices.py                 # reads generated/vendor (installed by program/setup_tools.py) and rewrites the file
    python tools/gen_notices.py --check         # only says whether the file is up to date (exit code 1 if not)

The Python packages are read from the *.dist-info folders of the vendor folder, so the versions are always the ones that are shipped.
The other components (ffmpeg, deno, QuickJS, the Android libraries) are listed here by hand: change the list below when they change.
"""
import argparse
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'THIRD_PARTY_NOTICES.md')

# (name, licence, where it is used, address)
OTHER = [
    ('FFmpeg (the "gpl" build of yt-dlp/FFmpeg-Builds)', 'GPL', 'Windows installer, Linux packages, AppImage, Flatpak: downloaded on the first start by setup_tools.py (not part of the repository)', 'https://github.com/yt-dlp/FFmpeg-Builds'),
    ('Deno', 'MIT', 'Windows installer and exe: downloaded by setup_tools.py; runs the JavaScript that YouTube needs', 'https://github.com/denoland/deno'),
    ('QuickJS', 'MIT', 'Android app (JavaScript runtime)', 'https://bellard.org/quickjs/'),
    ('CPython', 'PSF-2.0', 'Windows exe, Android app, AppImage (the Python interpreter)', 'https://www.python.org/'),
    ('youtubedl-android (JunkFood02 fork): library and ffmpeg modules', 'GPL-3.0', 'Android app (prepares Python and ffmpeg on the phone)', 'https://github.com/JunkFood02/youtubedl-android'),
    ('AndroidX (core-ktx, appcompat, activity-ktx)', 'Apache-2.0', 'Android app', 'https://developer.android.com/jetpack/androidx'),
]

HEAD = """# Third-party notices

YT Grabber itself is released under the [MIT licence](LICENSE). It uses the components below, each under its own licence. This file
is generated by `python tools/gen_notices.py`: do not edit it by hand.

**Please note.** Some components are under the GPL (FFmpeg, mutagen, and the Android library that prepares Python and ffmpeg on the
phone). The program does not modify them. The complete source code of YT Grabber is public in
<https://github.com/progliodario/YT-Grabber>, and the sources of the other components are in the addresses given here. Whoever
redistributes a package that contains these components should check that the combination meets the terms of every licence.

"""


def field(meta, name):
    m = re.search(r'^%s:\s*(.+)$' % re.escape(name), meta, re.M)
    return m.group(1).strip() if m else ''


def read_packages(vendor):
    """[(name, version, licence, address)] of the Python packages that are in the vendor folder."""
    rows = []
    for d in sorted(os.listdir(vendor)):
        if not d.endswith('.dist-info'):
            continue
        try:
            with open(os.path.join(vendor, d, 'METADATA'), encoding='utf-8', errors='replace') as f:
                meta = f.read().split('\n\n', 1)[0]
        except OSError:
            continue
        lic = field(meta, 'License-Expression') or field(meta, 'License')
        if not lic or len(lic) > 60:   # a whole licence text in the field: use the classifier instead
            cl = re.findall(r'^Classifier: License :: (?:OSI Approved :: )?(.+)$', meta, re.M)
            lic = '; '.join(cl) or 'see the package'
        url = field(meta, 'Home-page')
        if not url:
            m = re.search(r'^Project-URL: (?:Homepage|homepage|Source|Repository),\s*(\S+)', meta, re.M)
            url = m.group(1) if m else ''
        rows.append((field(meta, 'Name') or d.split('-')[0], field(meta, 'Version'), lic, url))
    return rows


def render(rows):
    out = [HEAD, '## Python packages (in the exe, the APK, the AppImage and the packages; yt-dlp is also installed by pip elsewhere)\n',
           '| Package | Version | Licence | Address |', '| --- | --- | --- | --- |']
    for name, ver, lic, url in rows:
        out.append('| %s | %s | %s | %s |' % (name, ver, lic, '<%s>' % url if url else ''))
    out += ['', '## Other components\n', '| Component | Licence | Where | Address |', '| --- | --- | --- | --- |']
    for name, lic, where, url in OTHER:
        out.append('| %s | %s | %s | <%s> |' % (name, lic, where, url))
    return '\n'.join(out) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--vendor', default=os.path.join(ROOT, 'generated', 'vendor'))
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    if not os.path.isdir(a.vendor):
        print('No vendor folder at %s: run python program/setup_tools.py first.' % a.vendor)
        return 2
    text = render(read_packages(a.vendor))
    if a.check:
        try:
            with open(OUT, encoding='utf-8', newline='') as f:
                same = f.read().replace('\r\n', '\n') == text
        except OSError:
            same = False
        print('THIRD_PARTY_NOTICES.md is %s' % ('up to date' if same else 'out of date: run python tools/gen_notices.py'))
        return 0 if same else 1
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('Written %s (%d packages)' % (OUT, len(read_packages(a.vendor))))
    return 0


if __name__ == '__main__':
    sys.exit(main())
